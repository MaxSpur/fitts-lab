begin;
do $$
declare owner1 uuid:=gen_random_uuid(); owner2 uuid:=gen_random_uuid(); rid1 uuid:=gen_random_uuid(); rid2 uuid:=gen_random_uuid(); pid uuid:=gen_random_uuid(); s jsonb; rev bigint; denied boolean:=false; begin
  insert into auth.users(id) values(owner1),(owner2);
  insert into public.instructors(user_id) values(owner1),(owner2);
  insert into public.rooms(id,owner_id,slug,title,status) values(rid1,owner1,'publication-test','Test one','closed'),(rid2,owner1,'publication-test','Test two','closed');
  insert into public.participants(id,room_id,client_key,token_hash,label,device) values(pid,rid1,gen_random_uuid(),repeat('a',64),'TEST','unspecified');
  insert into public.trials(trial_id,participant_id,room_id,data) values(gen_random_uuid(),pid,rid1,jsonb_build_object('id',gen_random_uuid(),'participant_id',pid,'path',jsonb_build_array(jsonb_build_object('x',1,'y',2,'t',3))));
  s:=public.read_fitts_public_snapshot('publication-test',null,0,500,null,null);
  assert s->'room'='null'::jsonb and jsonb_array_length(s->'trials')=0,'Default is private';
  perform public.publish_fitts_results(owner1,'publication-test',rid1,null);
  s:=public.read_fitts_public_snapshot('publication-test',null,0,500,null,null);rev:=(s->>'publication_revision')::bigint;
  assert (s->'room'->>'id')::uuid=rid1,'Published session returned even though admission has ended';
  assert jsonb_array_length(s->'trials')=1,'Raw measurements preserved';
  assert s->'participants'->0->>'token_hash' is null,'Credential hashes never exposed';
  assert s->'room'->>'owner_id' is null,'Auth owner not needed in public snapshot';
  assert s->'trials'->0->'path'->0->>'x'='1','Trajectory kept';
  s:=public.read_fitts_public_snapshot('publication-test',rid2,0,500,null,null);
  assert s->'room'='null'::jsonb,'An unpublished historical room is inaccessible';
  begin perform public.publish_fitts_results(owner2,'publication-test',rid1,rev); exception when insufficient_privilege then denied:=true; end;
  assert denied,'Another instructor cannot publish or revoke this slug';
  denied:=false;
  begin perform public.publish_fitts_results(owner1,'publication-test',null,rev-1); exception when serialization_failure then denied:=true; end;
  assert denied,'Stale publication UI cannot revoke a newer publication';
  perform public.publish_fitts_results(owner1,'publication-test',rid2,rev);
  s:=public.read_fitts_public_snapshot('publication-test',null,9999,500,rev,0);
  assert (s->'room'->>'id')::uuid=rid2 and (s->>'restarted')::boolean,'Switching published session restarts cursor';
  assert s->>'cursor'='0','No old-session rows retained';rev:=(s->>'publication_revision')::bigint;
  perform public.publish_fitts_results(owner1,'publication-test',null,rev);
  s:=public.read_fitts_public_snapshot('publication-test',null,0,500,null,null);
  assert s->'room'='null'::jsonb and jsonb_array_length(s->'trials')=0,'Revocation denies subsequent reads';
  assert (select count(*) from public.trials where room_id=rid1)=1,'Publishing never deletes or changes measurements';
  assert not has_function_privilege('anon','public.read_fitts_public_snapshot(text,uuid,bigint,integer,bigint,integer)','EXECUTE'),'No anonymous direct RPC';
  assert not has_function_privilege('authenticated','public.publish_fitts_results(uuid,text,uuid,bigint)','EXECUTE'),'No direct authenticated publication RPC';
  assert not has_table_privilege('anon','public.trials','SELECT'),'Existing table permissions unchanged';
  assert has_function_privilege('service_role','public.read_fitts_public_snapshot(text,uuid,bigint,integer,bigint,integer)','EXECUTE'),'Edge service can read';
end $$;
rollback;
select 'PASS: default-private, publication, revocation, ownership, compare-and-swap, historical sessions, raw paths and unchanged table permissions' as result;
